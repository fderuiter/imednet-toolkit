import contextlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path


def run_command(cmd, env=None, check=True):
    print(f"Running: {' '.join(cmd)}")
    subprocess.run(cmd, env=env, check=check)


def generate_adr_index(adr_dir: Path | None = None) -> None:
    """Generate docs/adr/index.rst catalog from markdown ADR records."""
    if adr_dir is None:
        adr_dir = Path("docs/adr")

    if not adr_dir.exists():
        print(f"Warning: ADR directory {adr_dir} not found.")
        return

    pattern = re.compile(r"^\d{4}-.+\.md$")
    records = [item for item in adr_dir.iterdir() if item.is_file() and pattern.match(item.name)]
    records.sort(key=lambda p: p.name)

    content = [
        "..",
        "   This file is auto-generated by scripts/build_docs.py.",
        "   Do not edit manually.",
        "",
        "Architecture Decision Records",
        "=============================",
        "",
        "This section documents the architectural decisions made for the imednet toolkit.",
        "",
        ".. toctree::",
        "   :maxdepth: 1",
        "",
    ]
    for record in records:
        content.append(f"   {record.stem}")
    content.append("")

    index_file = adr_dir / "index.rst"
    index_file.write_text("\n".join(content), encoding="utf-8")
    print(f"Generated ADR catalog at {index_file} ({len(records)} records).")


def build_and_stage_wheels(
    repo_root: Path | None = None, wheels_dir: Path | None = None
) -> list[Path]:
    """Build pure Python wheels for workspace packages and stage into docs/_build/wheels/."""
    if repo_root is None:
        repo_root = Path(__file__).resolve().parent.parent

    if wheels_dir is None:
        wheels_dir = repo_root / "docs" / "_build" / "wheels"

    wheels_dir.mkdir(parents=True, exist_ok=True)

    # Clean existing staged wheels
    for whl in wheels_dir.glob("*.whl"):
        with contextlib.suppress(OSError):
            whl.unlink()

    uv_bin = shutil.which("uv") or "uv"
    build_cmd = [
        uv_bin,
        "build",
        "--all-packages",
        "--wheel",
        "--out-dir",
        str(wheels_dir),
    ]

    print(f"Building pure Python workspace wheels into {wheels_dir}...")
    try:
        # Attempt offline build first to respect offline constraint
        subprocess.run(build_cmd + ["--offline"], check=True, cwd=str(repo_root))
    except (subprocess.CalledProcessError, FileNotFoundError):
        try:
            subprocess.run(build_cmd, check=True, cwd=str(repo_root))
        except (subprocess.CalledProcessError, FileNotFoundError) as exc:
            print(f"Warning: Failed to build wheels with uv: {exc}")

    # Remove workspace root placeholder wheel if present
    for placeholder in wheels_dir.glob("imednet_workspace-*.whl"):
        with contextlib.suppress(OSError):
            placeholder.unlink()

    staged = sorted(wheels_dir.glob("*.whl"))
    print(f"Staged {len(staged)} wheel artifact(s) in {wheels_dir}: {[w.name for w in staged]}")
    return staged


_REEXPORT_SUBMODULES: frozenset[str] = frozenset(
    {
        "imednet.models.engine",
        "imednet.utils.ast_eval",
    }
)

_REEXPORTED_MEMBERS_BY_MODULE: dict[str, str] = {
    "imednet.utils.job_poller": (
        "InvalidJobStateError, InvalidJobTransitionError, InvalidStateTransitionError"
    ),
    "imednet_workflows.uat.orchestrator": ("InvalidUATStateTransitionError, UATWorkflowState"),
}


def mark_reexport_stubs_noindex(api_dir: Path) -> None:
    """Add :noindex: / :exclude-members: to package __init__ and re-export stubs."""
    if not api_dir.exists():
        return

    automodule_pattern = re.compile(
        r"^(\.\. automodule:: ([A-Za-z0-9_.]+)\n)((?:   :[A-Za-z0-9_-]+:.*\n?)+)",
        re.MULTILINE,
    )

    for rst_file in sorted(api_dir.glob("*.rst")):
        text = rst_file.read_text(encoding="utf-8")
        has_children = "Subpackages\n-----------" in text or "Submodules\n----------" in text
        first_seen = False

        def _inject_noindex(match: re.Match[str], has_children: bool = has_children) -> str:
            nonlocal first_seen
            header = match.group(1)
            mod_name = match.group(2)
            opts_block = match.group(3)
            is_first = not first_seen
            first_seen = True

            extra_opts: list[str] = []
            should_noindex = (
                (is_first and has_children)
                or mod_name.startswith("imednet.spi.")
                or mod_name in _REEXPORT_SUBMODULES
            )
            if should_noindex and ":noindex:" not in opts_block:
                extra_opts.append("   :noindex:")

            excluded = _REEXPORTED_MEMBERS_BY_MODULE.get(mod_name)
            if excluded and ":exclude-members:" not in opts_block:
                extra_opts.append(f"   :exclude-members: {excluded}")

            if extra_opts:
                return header + "\n".join(extra_opts) + "\n" + opts_block
            return match.group(0)

        updated = automodule_pattern.sub(_inject_noindex, text)
        if updated != text:
            rst_file.write_text(updated, encoding="utf-8")


def main():
    api_dir = Path("docs/reference/api")

    print("Cleaning old API docs...")
    if api_dir.exists():
        shutil.rmtree(api_dir)

    print("Generating new API docs...")
    env = os.environ.copy()
    env["SPHINX_APIDOC_OPTIONS"] = "members,show-inheritance"

    # Core package
    run_command(
        [
            "sphinx-apidoc",
            "-o",
            str(api_dir),
            "packages/core/src/imednet",
            "packages/core/src/imednet/core",
            "packages/core/src/imednet/http",
            "-f",
            "-M",
            "--tocfile",
            "core",
        ],
        env=env,
    )

    # Other packages
    packages_dir = Path("packages")
    for pkg in sorted(packages_dir.iterdir(), key=lambda p: p.name):
        if pkg.is_dir() and pkg.name != "core":
            src_dir = pkg / "src"
            if src_dir.exists():
                subdirs = sorted([d for d in src_dir.iterdir() if d.is_dir()], key=lambda p: p.name)
                if subdirs:
                    target_dir = subdirs[0]
                    run_command(
                        [
                            "sphinx-apidoc",
                            "-o",
                            str(api_dir),
                            str(target_dir),
                            "-f",
                            "-M",
                            "--tocfile",
                            pkg.name,
                        ],
                        env=env,
                    )

    mark_reexport_stubs_noindex(api_dir)

    print("Generating ADR index...")
    generate_adr_index()

    print("Generating REST reference tables...")
    run_command([sys.executable, "scripts/generate_rest_reference.py"])

    print("Building and staging workspace wheels for interactive documentation...")
    staged_wheels_dir = Path("docs/_build/wheels")
    build_and_stage_wheels(wheels_dir=staged_wheels_dir)

    print("Validating mermaid diagrams...")
    run_command([sys.executable, "scripts/validate_diagrams.py"])

    print("Validating showcases...")
    run_command([sys.executable, "scripts/validate_showcases.py"])

    print("Type-checking documentation snippets...")
    run_command([sys.executable, "scripts/typecheck_docs.py"])

    print("Validating documentation...")
    run_command([sys.executable, "scripts/validate_docs.py"])

    print("Running doctests...")
    run_command(
        ["sphinx-build", "-b", "doctest", "-W", "--keep-going", "docs", "docs/_build/doctest"]
    )

    print("Checking hyperlinks...")
    run_command(
        [
            "sphinx-build",
            "-b",
            "linkcheck",
            "-W",
            "--keep-going",
            "docs",
            "docs/_build/linkcheck",
        ]
    )

    print("Building HTML...")
    run_command(["sphinx-build", "-b", "html", "-W", "--keep-going", "docs", "docs/_build/html"])

    # Ensure staged wheels are present in docs/_build/html/_static/wheels/
    html_wheels_dir = Path("docs/_build/html/_static/wheels")
    if staged_wheels_dir.exists():
        html_wheels_dir.mkdir(parents=True, exist_ok=True)
        for whl in staged_wheels_dir.glob("*.whl"):
            shutil.copy2(whl, html_wheels_dir / whl.name)


if __name__ == "__main__":
    main()
