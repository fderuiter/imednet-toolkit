def run_command(
    cmd: Sequence[str], env: Mapping[str, str] | None = None, check: bool = True
) -> None:
    print(f"Running: {' '.join(cmd)}")
    subprocess.run(cmd, env=env, check=check)


def generate_adr_index(adr_dir: Path | None = None) -> None:
    """Generate docs/adr/index.rst catalog from markdown ADR records."""
    if adr_dir is None:
        adr_dir = Path("docs/adr")

    if not adr_dir.exists():
        print(f"Warning: ADR directory {adr_dir} not found.")
        return

    pattern = re.compile(r"^\d{4}-.+\.md$")
    records = [item for item in adr_dir.iterdir() if item.is_file() and pattern.match(item.name)]
    records.sort(key=lambda p: p.name)

    content = [
        "..",
        "   This file is auto-generated by scripts/build_docs.py.",
        "   Do not edit manually.",
        "",
        "Architecture Decision Records",
        "=============================",
        "",
        "This section documents the architectural decisions made for the imednet toolkit.",
        "",
        ".. toctree::",
        "   :maxdepth: 1",
        "",
    ]
    for record in records:
        content.append(f"   {record.stem}")
    content.append("")

    index_file = adr_dir / "index.rst"
    index_file.write_text("\n".join(content), encoding="utf-8")
    print(f"Generated ADR catalog at {index_file} ({len(records)} records).")


BROWSER_WHEEL_SPECS: tuple[tuple[str, str], ...] = (
    ("imednet", "core"),
    ("imednet_workflows", "plugins-workflows"),
    ("imednet_plugins_sinks", "plugins-sinks"),
)

EXCLUDED_BROWSER_WHEEL_PREFIXES: tuple[str, ...] = (
    "imednet_workspace-",
    "imednet-workspace-",
    "apache_airflow_providers_imednet-",
    "apache-airflow-providers-imednet-",
    "imednet_tui-",
    "imednet-tui-",
)


def _find_browser_wheel(search_dir: Path, dist_prefix: str) -> Path | None:
    """Return the latest matching browser wheel in *search_dir* for *dist_prefix*."""
    matches = sorted(
        whl
        for whl in search_dir.glob(f"{dist_prefix}-*.whl")
        if whl.name.split("-", 1)[0] == dist_prefix
        and not whl.name.startswith(EXCLUDED_BROWSER_WHEEL_PREFIXES)
    )
    return matches[-1] if matches else None


def _restore_pyproject_backups(repo_root: Path, internal_packages: dict[str, Any]) -> None:
    """Restore tightened pyproject.toml files and remove any leftover .toml.bak files."""
    if internal_packages:
        tighten_dependencies.restore_files(internal_packages)
    packages_dir = repo_root / "packages"
    if packages_dir.is_dir():
        for backup_path in packages_dir.glob("*/*.toml.bak"):
            pyproject_path = backup_path.with_suffix("")
            shutil.copy2(backup_path, pyproject_path)
            backup_path.unlink()
            print(f"Restored {pyproject_path} from backup")


def build_and_stage_wheels(
    repo_root: Path | None = None,
    wheels_dir: Path | None = None,
    wheel_dir: Path | None = None,
) -> list[Path]:
    """Stage prebuilt or tightened pure Python browser wheels into docs/_static/wheels/."""
    if repo_root is None:
        repo_root = Path(__file__).resolve().parent.parent

    if wheels_dir is None:
        wheels_dir = repo_root / "docs" / "_static" / "wheels"

    wheels_dir.mkdir(parents=True, exist_ok=True)

    # Clean existing staged wheels
    for whl in wheels_dir.glob("*.whl"):
        with contextlib.suppress(OSError):
            whl.unlink()

    prebuilt_wheels: dict[str, Path] = {}
    if wheel_dir is not None and wheel_dir.is_dir():
        resolved_wheel_dir = wheel_dir.resolve()
        for dist_prefix, _ in BROWSER_WHEEL_SPECS:
            found = _find_browser_wheel(resolved_wheel_dir, dist_prefix)
            if found is not None:
                prebuilt_wheels[dist_prefix] = found

    if len(prebuilt_wheels) == len(BROWSER_WHEEL_SPECS):
        for dist_prefix, _ in BROWSER_WHEEL_SPECS:
            src_whl = prebuilt_wheels[dist_prefix]
            shutil.copy2(src_whl, wheels_dir / src_whl.name)
        staged = sorted(wheels_dir.glob("*.whl"))
        print(
            f"Reused {len(staged)} prebuilt wheel artifact(s) from {wheel_dir} in {wheels_dir}: "
            f"{[w.name for w in staged]}"
        )
        return staged

    uv_bin = shutil.which("uv") or "uv"
    build_cmd = [
        uv_bin,
        "build",
        "--all-packages",
        "--wheel",
        "--out-dir",
        str(wheels_dir),
    ]

    manifest_path = repo_root / ".release-please-manifest.json"
    internal_packages = (
        tighten_dependencies.get_internal_packages(manifest_path) if manifest_path.is_file() else {}
    )

    print(f"Building pure Python workspace wheels into {wheels_dir}...")
    try:
        for pkg_info in internal_packages.values():
            tighten_dependencies.tighten_file(pkg_info["pyproject_path"], internal_packages)

        try:
            # Attempt offline build first to respect offline constraint
            subprocess.run(build_cmd + ["--offline"], check=True, cwd=str(repo_root))
        except (subprocess.CalledProcessError, FileNotFoundError):
            try:
                subprocess.run(build_cmd, check=True, cwd=str(repo_root))
            except (subprocess.CalledProcessError, FileNotFoundError) as exc:
                print(f"Warning: Failed to build wheels with uv: {exc}")
    finally:
        _restore_pyproject_backups(repo_root, internal_packages)

    # Remove non-browser wheels (workspace root placeholder, Airflow server provider, CLI TUI)
    excluded_patterns = (
        "imednet_workspace-*.whl",
        "apache_airflow_providers_imednet-*.whl",
        "imednet_tui-*.whl",
    )
    for pattern in excluded_patterns:
        for excluded_whl in wheels_dir.glob(pattern):
            with contextlib.suppress(OSError):
                excluded_whl.unlink()

    # Prefer any prebuilt browser wheels supplied in wheel_dir over fallback rebuilds
    for dist_prefix, src_whl in prebuilt_wheels.items():
        for existing_whl in list(wheels_dir.glob(f"{dist_prefix}-*.whl")):
            if existing_whl.name.split("-", 1)[0] == dist_prefix:
                with contextlib.suppress(OSError):
                    existing_whl.unlink()
        shutil.copy2(src_whl, wheels_dir / src_whl.name)

    staged = sorted(wheels_dir.glob("*.whl"))
    print(f"Staged {len(staged)} wheel artifact(s) in {wheels_dir}: {[w.name for w in staged]}")
    return staged


def write_wheel_manifest(
    html_wheels_dir: Path | None = None, repo_root: Path | None = None
) -> Path:
    """Write _static/wheels/manifest.json under built HTML output for standalone Pyodide pages."""
    if repo_root is None:
        repo_root = Path(__file__).resolve().parent.parent
    if html_wheels_dir is None:
        html_wheels_dir = repo_root / "docs" / "_build" / "html" / "_static" / "wheels"

    html_wheels_dir.mkdir(parents=True, exist_ok=True)

    wheels: list[str] = []
    for dist_prefix, pkg_dir_name in BROWSER_WHEEL_SPECS:
        staged_matches = sorted(
            whl
            for whl in html_wheels_dir.glob(f"{dist_prefix}-*.whl")
            if not whl.name.startswith(EXCLUDED_BROWSER_WHEEL_PREFIXES)
        )
        if staged_matches:
            wheels.append(f"_static/wheels/{staged_matches[-1].name}")
            continue

        pyproject_file = repo_root / "packages" / pkg_dir_name / "pyproject.toml"
        pkg_version = "1.0.0"
        if pyproject_file.is_file():
            with pyproject_file.open("rb") as fh:
                pkg_version = str(tomllib.load(fh).get("project", {}).get("version", pkg_version))
        wheels.append(f"_static/wheels/{dist_prefix}-{pkg_version}-py3-none-any.whl")

    manifest_path = html_wheels_dir / "manifest.json"
    manifest_path.write_text(json.dumps({"wheels": wheels}, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote Pyodide wheel manifest at {manifest_path}: {wheels}")
    return manifest_path


SCOPED_INHERITED_MEMBERS = (
    "BaseModel, ImednetBaseModel, RootModel, Enum, str, int, Exception, BaseException, object"
)


def emit_curated_core_reference(api_dir: Path) -> None:
    """Emit curated imednet.core.rst for imednet.core.__all__ and register it in imednet.rst."""
    api_dir.mkdir(parents=True, exist_ok=True)
    core_rst = api_dir / "imednet.core.rst"
    core_rst.write_text(
        "imednet.core package\n"
        "====================\n\n"
        ".. automodule:: imednet.core\n"
        "   :inherited-members:\n"
        "   :members:\n"
        "   :show-inheritance:\n",
        encoding="utf-8",
    )

    imednet_rst = api_dir / "imednet.rst"
    if imednet_rst.exists():
        lines = imednet_rst.read_text(encoding="utf-8").splitlines()
        if "   imednet.core" not in lines:
            updated_lines: list[str] = []
            in_subpackages_toctree = False
            inserted = False
            for idx, line in enumerate(lines):
                if line.strip() == "Subpackages" and idx + 1 < len(lines):
                    in_subpackages_toctree = True
                elif in_subpackages_toctree and line.strip() == "Submodules":
                    if not inserted:
                        updated_lines.append("   imednet.core")
                        inserted = True
                    in_subpackages_toctree = False
                elif (
                    in_subpackages_toctree
                    and not inserted
                    and line.startswith("   imednet.")
                    and line.strip() > "imednet.core"
                ):
                    updated_lines.append("   imednet.core")
                    inserted = True
                updated_lines.append(line)
            imednet_rst.write_text("\n".join(updated_lines) + "\n", encoding="utf-8")


def scope_apidoc_inherited_members(api_dir: Path) -> None:
    """Scope :inherited-members: directives in generated apidoc RST files."""
    for rst_file in sorted(api_dir.glob("*.rst")):
        content = rst_file.read_text(encoding="utf-8")
        updated = content.replace(
            "   :inherited-members:\n",
            f"   :inherited-members: {SCOPED_INHERITED_MEMBERS}\n",
        )
        if updated != content:
            rst_file.write_text(updated, encoding="utf-8")


def require_sphinx_tools(*tools: str) -> dict[str, str]:
    """Verify required Sphinx CLI tools exist on PATH before mutating tracked files."""
    resolved: dict[str, str] = {}
    missing: list[str] = []
    for tool in tools:
        found = shutil.which(tool)
        if found is None:
            missing.append(tool)
        else:
            resolved[tool] = found
    if missing:
        joined = ", ".join(missing)
        raise FileNotFoundError(
            f"Required Sphinx tool(s) not found on PATH: {joined}. "
            "Run via 'uv run python scripts/build_docs.py' after syncing the workspace."
        )
    return resolved


def generate_api_reference(api_dir: Path | None = None) -> None:
    """Regenerate docs/reference/api RST files for all workspace packages via atomic staging."""
    if api_dir is None:
        api_dir = Path("docs/reference/api")

    require_sphinx_tools("sphinx-apidoc")
    api_dir.parent.mkdir(parents=True, exist_ok=True)

    print("Generating new API docs in staging directory...")
    env = os.environ.copy()
    env["SPHINX_APIDOC_OPTIONS"] = "inherited-members,members,show-inheritance"

    with tempfile.TemporaryDirectory(dir=api_dir.parent, prefix=".api_staging_") as tmp_root:
        tmp_root_path = Path(tmp_root)
        staging_dir = tmp_root_path / "api"
        staging_dir.mkdir(parents=True, exist_ok=True)

        # Core package (exclude internal core submodules and legacy http shim)
        run_command(
            [
                "sphinx-apidoc",
                "-o",
                str(staging_dir),
                "packages/core/src/imednet",
                "packages/core/src/imednet/core",
                "packages/core/src/imednet/http",
                "-f",
                "-M",
                "--tocfile",
                "core",
            ],
            env=env,
        )
        emit_curated_core_reference(staging_dir)

        # Other packages
        packages_dir = Path("packages")
        for pkg in sorted(packages_dir.iterdir()):
            if pkg.is_dir() and pkg.name != "core":
                src_dir = pkg / "src"
                if src_dir.exists():
                    subdirs = sorted(d for d in src_dir.iterdir() if d.is_dir())
                    if subdirs:
                        target_dir = subdirs[0]
                        run_command(
                            [
                                "sphinx-apidoc",
                                "-o",
                                str(staging_dir),
                                str(target_dir),
                                "-f",
                                "-M",
                                "--tocfile",
                                pkg.name,
                            ],
                            env=env,
                        )

        scope_apidoc_inherited_members(staging_dir)

        print("Replacing API docs with staged output...")
        backup_dir = tmp_root_path / "backup"
        if api_dir.exists():
            shutil.move(str(api_dir), str(backup_dir))
        try:
            shutil.move(str(staging_dir), str(api_dir))
        except Exception:
            if backup_dir.exists() and not api_dir.exists():
                shutil.move(str(backup_dir), str(api_dir))
            raise


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parse CLI arguments for building documentation."""
    parser = argparse.ArgumentParser(
        description="Build and validate Sphinx documentation and interactive Pyodide wheels."
    )
    parser.add_argument(
        "--wheel-dir",
        type=Path,
        default=None,
        help="Optional directory containing prebuilt workspace wheels to stage.",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    require_sphinx_tools("sphinx-apidoc", "sphinx-build")
    generate_api_reference()

    print("Generating ADR index...")
    generate_adr_index()

    print("Generating REST reference tables...")
    run_command([sys.executable, "scripts/generate_rest_reference.py"])

    print("Building and staging workspace wheels for interactive documentation...")
    build_and_stage_wheels(wheel_dir=args.wheel_dir)

    print("Validating mermaid diagrams...")
    run_command([sys.executable, "scripts/validate_diagrams.py"])

    print("Validating showcases...")
    run_command([sys.executable, "scripts/validate_showcases.py"])

    print("Type-checking documentation snippets...")
    run_command([sys.executable, "scripts/typecheck_docs.py"])

    print("Running doctests...")
    run_command(
        ["sphinx-build", "-b", "doctest", "-W", "--keep-going", "docs", "docs/_build/doctest"]
    )

    print("Checking hyperlinks...")
    run_command(
        [
            "sphinx-build",
            "-b",
            "linkcheck",
            "-W",
            "--keep-going",
            "docs",
            "docs/_build/linkcheck",
        ]
    )

    print("Building HTML...")
    run_command(["sphinx-build", "-b", "html", "-W", "--keep-going", "docs", "docs/_build/html"])

    # Ensure staged wheels are present in docs/_build/html/_static/wheels/
    # and clean up temporary staging directory so the git working tree stays clean.
    html_wheels_dir = Path("docs/_build/html/_static/wheels")
    static_wheels_dir = Path("docs/_static/wheels")
    if static_wheels_dir.exists():
        html_wheels_dir.mkdir(parents=True, exist_ok=True)
        staged_wheels = list(static_wheels_dir.glob("*.whl"))
        if staged_wheels:
            staged_names = {whl.name for whl in staged_wheels}
            for existing_whl in html_wheels_dir.glob("*.whl"):
                if existing_whl.name not in staged_names:
                    with contextlib.suppress(OSError):
                        existing_whl.unlink()
            for whl in staged_wheels:
                shutil.copy2(whl, html_wheels_dir / whl.name)
        shutil.rmtree(static_wheels_dir, ignore_errors=True)
    write_wheel_manifest(html_wheels_dir)

    print("Validating documentation, rendered API reference, and SEO artifacts...")
    run_command([sys.executable, "scripts/validate_docs.py", "--require-html"])


if __name__ == "__main__":
    main()
